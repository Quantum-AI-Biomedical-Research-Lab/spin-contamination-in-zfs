def add(sec, quantity, printed, computed, source, how):
    """printed: the numbers as they appear in the text (strings); computed: matching floats.
    Prefixes give the rounding kind of the prose: none = nearest at the printed precision, '<' = upper bound rounded
    up (printed >= computed, within one unit of the last digit), '>' = lower bound rounded down, '~' = 'about' (two
    significant figures, within 5%)."""
    comp = computed if isinstance(computed, (list, tuple)) else [computed]
    for ps0, c in zip(printed, comp):
        kind = ps0[0] if ps0[0] in '<>~' else ''; ps = ps0.lstrip('<>~')
        if kind:
            d = len(ps.split('.')[1]) if '.' in ps else 0; u = 10 ** (-d); pv = float(ps.replace(',', ''))
            ok = {'<': -1e-12 <= pv - c < u, '>': -1e-12 <= c - pv < u, '~': abs(pv - c) <= 0.05 * abs(c)}[kind]
        elif isinstance(c, (int, np.integer)) and not isinstance(c, bool):
            ok = int(ps.replace(',', '')) == int(c)
        elif 'e' in ps:                                   # scientific notation: compare the mantissa
            m_, e_ = ps.split('e'); d = len(m_.split('.')[1]) if '.' in m_ else 0
            ok = abs(float(m_) - round(float(c) / 10 ** int(e_), d)) < 10 ** (-d) / 2 + 1e-12
        else:
            d = len(ps.split('.')[1]) if '.' in ps else 0
            ok = abs(float(ps) - round(float(c), d)) < 10 ** (-d) / 2 + 1e-12
        if not ok:
            bad.append((sec, quantity, ps0, c))
    rows.append([sec, quantity, '; '.join(printed), '; '.join(repr(float(c)) if not isinstance(c, (int, np.integer)) else str(c) for c in comp), source, how])

